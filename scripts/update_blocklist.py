#!/usr/bin/env python3
"""Builds Wink's network blocklist (Resources/blocklist/domains.txt).

Sources: EasyPrivacy + EasyList (https://easylist.to), dual licensed under
GPLv3 and CC BY-SA 3.0. Wink ships the derived list under CC BY-SA 3.0 with
attribution (see NOTICE in the output directory).

Only domain-anchored rules ("||tracker.example^", optionally with
"$third-party" or resource-type options) are kept: Wink blocks at the network level by domain, never blocks first-party
requests, and never blocks top-level navigations. Rules with type or site
restrictions are skipped to keep breakage low.

Usage: python3 -I scripts/update_blocklist.py Resources/blocklist
"""
import datetime
import os
import re
import sys
import urllib.request

SOURCES = {
    "EasyPrivacy": "https://easylist.to/easylist/easyprivacy.txt",
    "EasyList": "https://easylist.to/easylist/easylist.txt",
}

RULE = re.compile(r"^\|\|([a-z0-9][a-z0-9.-]*\.[a-z]{2,})\^(?:\$(.*))?$")
# Resource-type options are widened to "everything from this domain" (these are
# dedicated ad/tracker hosts); site-specific or behavior-changing options are not.
ALLOWED_OPTIONS = {"third-party", "3p", "script", "image", "xmlhttprequest", "subdocument", "ping", "media",
                   "object", "stylesheet", "font", "websocket", "other", "important", "all", "popup"}

# Never block these registrable domains outright (too much collateral breakage).
GUARD = {
    "google.com", "googleapis.com", "gstatic.com", "youtube.com", "ytimg.com", "googlevideo.com",
    "facebook.com", "fbcdn.net", "instagram.com", "twitter.com", "x.com", "twimg.com",
    "microsoft.com", "live.com", "office.com", "apple.com", "icloud.com", "amazon.com",
    "amazonaws.com", "cloudfront.net", "akamaihd.net", "akamaized.net", "cloudflare.com",
    "jsdelivr.net", "unpkg.com", "github.com", "githubusercontent.com", "wikipedia.org",
    "linkedin.com", "reddit.com", "redditstatic.com", "yahoo.com", "bing.com", "duckduckgo.com",
}


def fetch(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "wink-blocklist-builder"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8", "replace")


def registrable(domain: str) -> str:
    parts = domain.split(".")
    return ".".join(parts[-2:])


def main() -> int:
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "Resources/blocklist"
    os.makedirs(out_dir, exist_ok=True)
    domains: set[str] = set()
    counts = {}
    for name, url in SOURCES.items():
        text = fetch(url)
        before = len(domains)
        for raw in text.splitlines():
            line = raw.strip().lower()
            if not line or line.startswith(("!", "[", "@@")) or "#" in line:
                continue
            match = RULE.match(line)
            if not match:
                continue
            domain, options = match.group(1), match.group(2)
            if options:
                opts = set(options.split(","))
                if not opts <= ALLOWED_OPTIONS or opts == {"popup"}:
                    continue
            if domain in GUARD:
                continue
            domains.add(domain)
        counts[name] = len(domains) - before

    # Drop subdomains already covered by a listed parent domain.
    pruned = sorted(d for d in domains if not any(d.endswith("." + p) for p in _parents(d) if p in domains))
    stamp = datetime.date.today().isoformat()
    header = [
        "# Wink network blocklist — generated by scripts/update_blocklist.py on " + stamp,
        "# Derived from EasyPrivacy and EasyList (https://easylist.to), CC BY-SA 3.0.",
        "# One domain per line; a rule also matches its subdomains.",
    ]
    with open(os.path.join(out_dir, "domains.txt"), "w") as handle:
        handle.write("\n".join(header + pruned) + "\n")
    with open(os.path.join(out_dir, "NOTICE"), "w") as handle:
        handle.write(
            "Wink's blocklist (domains.txt) is derived from EasyPrivacy and EasyList by The EasyList authors\n"
            "(https://easylist.to/), used under the Creative Commons Attribution-ShareAlike 3.0 license\n"
            "(https://creativecommons.org/licenses/by-sa/3.0/). The derived list is distributed under the same license.\n")
    print(f"{len(pruned)} domains ({', '.join(f'{k}: +{v}' for k, v in counts.items())}) -> {out_dir}/domains.txt")
    return 0


def _parents(domain: str):
    parts = domain.split(".")
    for i in range(1, len(parts) - 1):
        yield ".".join(parts[i:])


if __name__ == "__main__":
    sys.exit(main())
